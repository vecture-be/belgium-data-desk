import assert from 'node:assert/strict';
import {classifyVersionChange,versionPassport,dependencyImpact,changeDecision,validatePassport} from './version-intelligence.mjs';
const rec={id:'national:belgian-population',title:'Population by municipality',publisher:'Statbel',updatedAt:'2026-11-20',landingPage:'https://statbel.fgov.be/data'};
const d='https://statbel.fgov.be/data.csv';
const past='2026-11-14T01:00:00Z',now='2026-11-20T01:00:00Z';
const base={ds:rec.id,url:d,checkedAt:now,sha256:'abc123',profile:{rows:110,rows_exact:true,row_set:'set2',fingerprint:'schema1'},content_since:now,observed_since:past};
const change=(props={})=>({...base,change:{seen_at:now,since:past,rows:{before:100,after:110},distinct_rows_added:10,distinct_rows_removed:0,...props}});
const added=change({coverage:[{column:'jaar',before:['2023','2024'],after:['2023','2025']}]});
assert.equal(classifyVersionChange(added).kind,'append_with_period_extension');
assert.equal(classifyVersionChange(change()).kind,'append_only_observed');
assert.equal(classifyVersionChange(change({distinct_rows_removed:2})).kind,'rows_replaced_or_removed');
assert.equal(classifyVersionChange(change({columns_removed:['nis']})).kind,'potential_breaking_change');
assert.equal(classifyVersionChange(change({alerts:['rows_dropped']})).severity,'review');
assert.equal(classifyVersionChange(change({columns_added:['extra']})).kind,'schema_evolution');
assert.equal(classifyVersionChange(change({distinct_rows_added:undefined,distinct_rows_removed:undefined})).kind,'content_change_unresolved');
assert.equal(classifyVersionChange({...base,unchanged:true,row_order_unstable:true}).kind,'no_semantic_change');
assert.equal(classifyVersionChange({...base,change:{seen_at:past},unchanged:true}).kind,'unchanged');
assert.equal(classifyVersionChange(base).kind,'unassessed');
assert.equal(classifyVersionChange({...base,profile:{rows:10,rows_exact:false}}).kind,'not_observed');
const p=versionPassport(rec,added);
assert.deepEqual(validatePassport(p,rec,added),[]);
assert.equal(p.publisher_revision,null);assert.equal(p.publisher_release,null);
assert.equal(p.manifestation.order_independent_row_set,'set2');
assert.equal(p.citation.publisher_record_url,rec.landingPage);
assert.equal(p.change_classification.kind,'append_with_period_extension');
const partial={...base,profile:{rows:12,rows_exact:false,fingerprint:'partial'},sha256:null};
const pp=versionPassport(rec,partial);
assert.equal(pp.manifestation.order_independent_row_set,null);
assert.equal(pp.observation.extent,'first_bytes');
assert.deepEqual(validatePassport(pp,rec,partial),[]);
assert.ok(validatePassport({...p,publisher_revision:'v1'},rec,added).includes('publisher_release_invented'));
const impact=dependencyImpact(rec,added);
assert.equal(impact.edges.length,4);
assert.ok(impact.affected_outputs.includes('mcp:get_dataset:'+rec.id));
assert.ok(!JSON.stringify(impact).includes('belgian_statistics'),'do not assert an unsupported live-tool dependency');
assert.equal(changeDecision(change({alerts:['columns_removed']}),rec).automatic_release_block,false);
assert.equal(versionPassport({},added),null);
console.log('version intelligence: semantic, lineage, limitation and contract checks pass');
