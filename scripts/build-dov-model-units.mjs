// Builds dov-model-units.mjs: the names of the units in DOV's Geological 3D model (G3Dv3.1), keyed by the band names of its multiband
// coverage, taken from DOV's own layer titles. Run by hand when DOV publishes a new model version (then also update G3D_MODEL in dov.mjs):
//   node scripts/build-dov-model-units.mjs
// The DOV code lists cannot be used for this: the model's unit codes reuse the same short codes in different eras (KR_Ma is
// Maastricht, PA_Ma is Maldegem), so a code-list lookup gives wrong names.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const MODEL="g3dv3_1";
const here=path.dirname(fileURLToPath(import.meta.url));
const caps=await (await fetch(`https://www.dov.vlaanderen.be/geoserver/${MODEL}/wfs?service=WFS&version=2.0.0&request=GetCapabilities`,{headers:{accept:"*/*"}})).text();
const describe=await (await fetch(`https://www.dov.vlaanderen.be/geoserver/wcs?service=WCS&version=2.0.1&request=DescribeCoverage&coverageId=${MODEL}__${MODEL}_multiband`,{headers:{accept:"*/*"}})).text();
const titles=new Map([...caps.matchAll(/<Name>(?:[\w-]+:)?([^<]+)<\/Name>\s*<Title>([^<]*)<\/Title>/g)].map(m=>[m[1],m[2]]));
const bands=[...describe.matchAll(/swe:field name="([^"]+)"/g)].map(m=>m[1]);
if(titles.size<100||bands.length<50)throw new Error("unexpected capabilities: "+titles.size+" titles, "+bands.length+" bands");
const tidy=t=>t.replace(/^G3Dv3\.1(?: \d+)?, /,"").replace(/^(isohypsen van (basis|top)|isopachen|boringen met|breuken in (basis|top)|voorkomen van) /,"")
  .replace(/\s+/g," ").replace(/\bFm\b/g,"Formatie").replace(/\bLd\b/g,"Lid").replace(/\bGr\b(?= van)/g,"Groep").trim();
const units={};const missing=[];
for(const band of bands){
  if(band==="g_Topografie")continue;
  const code=band.replace(/^g_/,"").replace(/_[bt]$/,"");
  const title=["_b_ih","_t_ih","_ip","_v","_bo","_b_br"].map(s=>titles.get(MODEL+"_"+code+s)).find(Boolean);
  if(title)units[code]=tidy(title);else missing.push(code);
}
const out=`// Generated by scripts/build-dov-model-units.mjs from DOV's ${MODEL} layer titles (${new Date().toISOString().slice(0,10)}). Do not edit.
// Unit names of the Geological 3D model of Flanders, keyed by multiband coverage band (without the g_ prefix and _b/_t suffix).
export const G3D_UNITS=${JSON.stringify(units,null,0).replace(/","/g,'",\n  "').replace(/^\{/,"{\n  ").replace(/\}$/,"\n}")};
`;
fs.writeFileSync(path.join(here,"..","dov-model-units.mjs"),out);
console.log(JSON.stringify({units:Object.keys(units).length,missing}));
