// Builds relay-index.mjs: the allow-list of CSV/TSV files the Worker may fetch for the browser relay and the MCP preview_dataset tool.
// Each approved HTTPS URL gets an opaque id (f_ + 32 hex of its SHA-256); clients only ever send that id, never a URL.
// Shared by scripts/harvest.mjs (after a fresh harvest) and scripts/snapshot.mjs (after downloading a deployed catalogue).
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { ASSETS } from "../public/dataset-atlas-v1.mjs";
import { EXTRA_ATLAS_ASSETS } from "../public/dataset-atlas-extra-v1.mjs";
import { COMPLETENESS_ASSETS } from "../public/dataset-atlas-completeness-v1.mjs";
import { COMPLETENESS_ASSETS_V2 } from "../public/dataset-atlas-completeness-v2.mjs";
import { COMPLETENESS_ASSETS_V3 } from "../public/dataset-atlas-completeness-v3.mjs";
import { COMPLETENESS_ASSETS_V4 } from "../public/dataset-atlas-completeness-v4.mjs";

const __dirname=path.dirname(fileURLToPath(import.meta.url));
export const RELAY_INDEX_PATH=path.resolve(__dirname,"../relay-index.mjs");
export const CURATED_RELAY_ASSETS=[...ASSETS,...EXTRA_ATLAS_ASSETS,...COMPLETENESS_ASSETS,...COMPLETENESS_ASSETS_V2,...COMPLETENESS_ASSETS_V3,...COMPLETENESS_ASSETS_V4];

const clean=s=>String(s??"").replace(/\s+/g," ").trim();
export const relayId=url=>"f_"+createHash("sha256").update(String(url)).digest("hex").slice(0,32);
const relayDistributionParts=d=>Array.isArray(d)
  ?{name:d[0]||"",format:d[1]||"",url:d[4]||"",byteSize:Number.isFinite(Number(d[5]))?Number(d[5]):null}
  :{name:d?.name||"",format:d?.format||"",url:d?.url||"",byteSize:Number.isFinite(Number(d?.byteSize))?Number(d.byteSize):null};
const safeRelayUrl=value=>{
  try{
    const u=new URL(String(value||""));
    if(u.protocol!=="https:"||u.username||u.password)return null;
    const h=u.hostname.toLowerCase().replace(/^\[|\]$/g,"").replace(/\.$/,"");
    if(!h||h==="localhost"||h.endsWith(".localhost")||h.endsWith(".local")||h.endsWith(".internal"))return null;
    return u;
  }catch{return null}
};
const relayableDistribution=d=>{
  const x=relayDistributionParts(d),u=safeRelayUrl(x.url);if(!u)return false;
  const hay=(x.name+" "+x.format+" "+u.pathname).toLowerCase();
  return /\b(?:csv|tsv)\b|file-type\/(?:csv|tsv)|\.(?:csv|tsv)$/.test(hay);
};
function relayHosts(host){
  const h=String(host||"").toLowerCase().replace(/\.$/,"");
  return h?[h]:[];
}

/** Items are catalogue records with `distributions` (objects, or the thin national array form). Returns the sorted index object. */
export function buildRelayIndex(items){
  const entries=new Map(),datasets=new Set();
  for(const item of items||[]){
    let matched=false;
    for(const d of item?.distributions||[]){
      if(!relayableDistribution(d))continue;
      const {url,format,byteSize}=relayDistributionParts(d),u=safeRelayUrl(url),id=relayId(url);
      if(!u)continue;matched=true;
      const existing=entries.get(id);
      if(existing&&existing.url!==String(url))throw new Error("relay id collision for "+id);
      const knownSizes=[existing?.byteSize,byteSize].filter(x=>Number.isFinite(x)&&x>=0);
      entries.set(id,{url:String(url),hosts:relayHosts(u.hostname),format:clean(format||existing?.format||"CSV"),byteSize:knownSizes.length?Math.max(...knownSizes):null});
    }
    if(matched)datasets.add(item.id||item.datasetId||item.title);
  }
  let knownSmall=0,knownLarge=0,unknownSize=0;
  for(const entry of entries.values())entry.byteSize==null?unknownSize++:entry.byteSize<=8*1024*1024?knownSmall++:knownLarge++;
  return{index:Object.fromEntries([...entries.entries()].sort(([a],[b])=>a.localeCompare(b))),stats:{entries:entries.size,datasets:datasets.size,knownSmall,knownLarge,unknownSize}};
}

export function writeRelayIndex(items,file=RELAY_INDEX_PATH){
  const {index,stats}=buildRelayIndex([...CURATED_RELAY_ASSETS,...(items||[])]);
  fs.writeFileSync(file,"// Generated by scripts/relay-index-lib.mjs. Do not edit manually.\nexport const RELAY_INDEX=Object.freeze("+JSON.stringify(index)+");\n");
  console.log("[relay-index] wrote "+stats.entries+" unique approved CSV/TSV relay targets across "+stats.datasets+" catalogue records; unique known ≤8 MiB "+stats.knownSmall+", unique known >8 MiB "+stats.knownLarge+", unique unknown size "+stats.unknownSize);
  return stats;
}
